/// <reference types="node" />
// Syncs the private certificate database to the public one.
//
//   private/certificates.json   (gitignored) names + emails. Edit this.
//   src/data/certificates.json  (committed)  names, IDs, program, batch, date. Generated.
//   private/share-links.csv     (gitignored) each graduate's public certificate link, to send out. Generated.
//
// Run: bun run certs
import { readFileSync, writeFileSync } from "node:fs";

const SITE = "https://www.neutrinoscienceclub.org";

type PrivateCert = {
  id: string;
  full_name: string;
  emails: string[];
  program?: string;
  batch?: string;
  completed_on?: string | null;
};
type PrivateDb = {
  _readme: string;
  certificates: PrivateCert[];
  defaults: { program: string; batch: string; completed_on: string | null };
};

const PRIVATE = "private/certificates.json";
const PUBLIC = "src/data/certificates.json";
const CSV = "private/share-links.csv";

const db: PrivateDb = JSON.parse(readFileSync(PRIVATE, "utf8"));

const ids = new Set<string>();
for (const c of db.certificates) {
  if (!/^NSC-B\d+\d{3}$/.test(c.id)) throw new Error(`Bad id format: ${c.id}`);
  if (ids.has(c.id)) throw new Error(`Duplicate id ${c.id}`);
  ids.add(c.id);
  c.emails = c.emails.map((e) => e.trim().toLowerCase());
}

const certificates = db.certificates.map((c) => ({
  id: c.id,
  full_name: c.full_name,
  program: c.program ?? db.defaults.program,
  batch: c.batch ?? db.defaults.batch,
  completed_on: c.completed_on ?? db.defaults.completed_on,
}));

writeFileSync(PRIVATE, JSON.stringify(db, null, 2) + "\n");
writeFileSync(
  PUBLIC,
  JSON.stringify({ _readme: "Generated by `bun run certs` from private/certificates.json. Do not edit by hand.", certificates }, null, 2) + "\n",
);
const csv = [
  "id,full_name,email,link",
  ...db.certificates.map((c) => [c.id, c.full_name, c.emails.join(" / "), `${SITE}/certificate/${c.id}`].map((v) => `"${v}"`).join(",")),
];
writeFileSync(CSV, csv.join("\n") + "\n");

console.log(`${certificates.length} certificates → ${PUBLIC}`);
console.log(`Share links → ${CSV}`);
