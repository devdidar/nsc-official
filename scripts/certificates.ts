/// <reference types="node" />
// Syncs the private certificate database to the public one.
//
//   private/certificates.json   (gitignored) names, emails, passcodes. Edit this.
//   src/data/certificates.json  (committed)  names + hashed emails/passcodes. Generated.
//   private/passcodes.csv       (gitignored) list to share with participants. Generated.
//
// Run: bun run certs
import { readFileSync, writeFileSync } from "node:fs";
import { hashEmail, hashPasscode, newPasscode, newSalt, normalizeEmail } from "../src/lib/certificate-crypto";

type PrivateCert = {
  id: string;
  full_name: string;
  emails: string[];
  passcode: string;
  program?: string;
  batch?: string;
  completed_on?: string | null;
};
type PrivateDb = {
  _readme: string;
  certificates: PrivateCert[];
  defaults: { program: string; batch: string; completed_on: string | null };
};
type PublicCert = {
  id: string;
  full_name: string;
  program: string;
  batch: string;
  completed_on: string | null;
  email_hashes: string[];
  passcode_salt: string;
  passcode_hash: string;
};

const PRIVATE = "private/certificates.json";
const PUBLIC = "src/data/certificates.json";
const CSV = "private/passcodes.csv";

const db: PrivateDb = JSON.parse(readFileSync(PRIVATE, "utf8"));
let previous: PublicCert[] = [];
try {
  previous = JSON.parse(readFileSync(PUBLIC, "utf8")).certificates;
} catch {}

const ids = new Set<string>();
const emails = new Set<string>();
const passcodes = new Set(db.certificates.map((c) => c.passcode).filter(Boolean));

for (const c of db.certificates) {
  if (ids.has(c.id)) throw new Error(`Duplicate id ${c.id}`);
  ids.add(c.id);
  c.emails = c.emails.map(normalizeEmail);
  for (const e of c.emails) {
    if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(e)) throw new Error(`Invalid email for ${c.id}: ${e}`);
    if (emails.has(e)) throw new Error(`Email used twice: ${e} (${c.id})`);
    emails.add(e);
  }
  if (!c.passcode) {
    let code;
    do code = newPasscode();
    while (passcodes.has(code));
    passcodes.add(code);
    c.passcode = code;
  }
}

const certificates: PublicCert[] = db.certificates.map((c) => {
  // Keep the old salt/hash when the passcode hasn't changed, so the generated file stays stable.
  const prev = previous.find((p) => p.id === c.id);
  const reuse = prev && hashPasscode(c.passcode, prev.passcode_salt) === prev.passcode_hash;
  const salt = reuse ? prev.passcode_salt : newSalt();
  return {
    id: c.id,
    full_name: c.full_name,
    program: c.program ?? db.defaults.program,
    batch: c.batch ?? db.defaults.batch,
    completed_on: c.completed_on ?? db.defaults.completed_on,
    email_hashes: c.emails.map(hashEmail),
    passcode_salt: salt,
    passcode_hash: reuse ? prev.passcode_hash : hashPasscode(c.passcode, salt),
  };
});

writeFileSync(PRIVATE, JSON.stringify(db, null, 2) + "\n");
writeFileSync(
  PUBLIC,
  JSON.stringify({ _readme: "Generated by `bun run certs` from private/certificates.json. Do not edit by hand.", certificates }, null, 2) + "\n",
);
const csv = ["id,full_name,email,passcode", ...db.certificates.map((c) => [c.id, c.full_name, c.emails.join(" / "), c.passcode].map((v) => `"${v}"`).join(","))];
writeFileSync(CSV, csv.join("\n") + "\n");

console.log(`${certificates.length} certificates → ${PUBLIC}`);
console.log(`Passcodes for sharing → ${CSV}`);
